/**
 * 「自分だけに見えるログ」を**いま画面に出してよいか**の判定（§5.1 `V-286`）。
 *
 * 🔴**なぜ純関数にするか**＝CPU 対戦では**CPU の効果も人間のブラウザで解決される**ので、
 *   「自分だけに見える行」をそのまま描くと**CPU の非公開情報（相手のデッキの一番上など）が
 *   人間に見える**＝立場が逆なだけで `V-285` と同じ不公平になる。
 *   判定を画面の条件式に散らすと片方の枝だけ抜ける型の漏れが起きるので1本に寄せ、golden で両方向を固定する。
 *
 * 🔑**規約＝CPU が手番を握っている間は自分だけの行も出さない**（出さない側に倒す）。
 *   ⚠代償＝相手ターン中に発火した**自分の**「見る」効果の結果も出なくなる。
 *   **情報を1つ取り逃すほうが、相手の伏せ札が見えるより軽い**という判断（`V-285` と同じ向き）。
 * ⚠オンライン対戦（`isCpuBattle=false`）では**常に出してよい**＝engine を走らせているのは自分だけ。
 */
export function canShowPrivateLog(o: { isCpuBattle: boolean; cpuIsActing: boolean }): boolean {
  return !(o.isCpuBattle && o.cpuIsActing);
}
