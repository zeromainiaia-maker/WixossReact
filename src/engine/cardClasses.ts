/**
 * **シグニのクラスを1つずつに分ける唯一の式**（2026-10-23 ユーザー裁定）。
 *
 * 🔑裁定＝「精武はクラスではなくその上位の分類」＝`精武：アーム` のクラスは **アーム** の1つ、
 *   `精武：アーム/ウェポン` は **アーム・ウェポン** の2種類。`/`（全角 `／` も）で区切り、`：` があればその後ろだけを取る。
 *   ⚠後ろ側が頭を省いた形（`精武：アーム/ウェポン` の `ウェポン`）も、下位だけを取るので補う必要がない。
 *   ⚠`：` の無いクラス（`精元`・`解放派`・`世怜音女学院`）はそのまま1つ。
 * 🔴旧＝箇所ごとに分け方がばらばらだった＝①全角 `／` だけで分ける（データの大半は半角 `/`＝複数クラスのシグニを分けられない）
 *   ②`：` で分けて上位も数える（`精武：アーム` が 精武・アーム の2つ）③`・/` で分けて `：` を残す（`精武：アーム` が1つ）。
 *   同じ「クラスが合計N種類」が、効果の経路によって違う数を返していた。
 * ⚠**「＜精武＞のシグニ」のように上位の分類を名指しする照合はここを使わない**（`matchesFilter` の文字列照合のまま当たる）。
 *   ここはクラスを**数える／共有を見る／宣言の候補にする**ための式。
 */
export function signiClassesOf(cardClass: string | undefined): string[] {
  const out: string[] = [];
  for (const part of (cardClass ?? '').replace(/[＜＞]/g, '').split(/[/／]/)) {
    const lower = part.split(/[：:]/).pop()?.trim() ?? '';
    if (lower && lower !== '-' && !out.includes(lower)) out.push(lower);
  }
  return out;
}
